"""
Word Document (.docx) Generator for Ayush AI using python-docx.
Saves documents into files/word/ with professional typography and formatting.
"""

import datetime
from pathlib import Path
from typing import Dict, Any
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from config import WORD_DIR
from agent.permissions import validate_safe_path
from agent.logger import logger


def create_word(filename: str, title: str, content: str) -> Dict[str, Any]:
    """
    Creates a formatted Microsoft Word document (.docx) and saves it in files/word/.
    """
    clean_name = filename.strip()
    if not clean_name.endswith(".docx"):
        clean_name += ".docx"

    target_path = validate_safe_path(WORD_DIR / clean_name, allowed_roots=[WORD_DIR])
    logger.info(f"Generating Word document '{clean_name}' at {target_path}")

    try:
        doc = Document()

        # Adjust page margins
        for section in doc.sections:
            section.top_margin = Inches(1)
            section.bottom_margin = Inches(1)
            section.left_margin = Inches(1)
            section.right_margin = Inches(1)

        # Document Header / Title
        title_para = doc.add_paragraph()
        title_run = title_para.add_run(title)
        title_run.font.name = "Calibri"
        title_run.font.size = Pt(24)
        title_run.font.bold = True
        title_run.font.color.rgb = RGBColor(31, 78, 121)  # Deep Navy Accent
        title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

        # Subtitle / Metadata
        meta_para = doc.add_paragraph()
        created_str = datetime.datetime.now().strftime("%B %d, %Y - %I:%M %p")
        meta_run = meta_para.add_run(f"Generated by Ayush AI | {created_str}")
        meta_run.font.name = "Calibri"
        meta_run.font.size = Pt(10)
        meta_run.font.italic = True
        meta_run.font.color.rgb = RGBColor(120, 120, 120)
        meta_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

        doc.add_paragraph().paragraph_format.space_after = Pt(12)

        # Process Body Content
        lines = content.split("\n")
        for line in lines:
            line_str = line.strip()
            if not line_str:
                doc.add_paragraph()
                continue

            if line_str.startswith("### "):
                p = doc.add_heading(line_str.lstrip("#").strip(), level=3)
                p.paragraph_format.space_before = Pt(8)
                p.paragraph_format.space_after = Pt(4)
            elif line_str.startswith("## "):
                p = doc.add_heading(line_str.lstrip("#").strip(), level=2)
                p.paragraph_format.space_before = Pt(12)
                p.paragraph_format.space_after = Pt(4)
            elif line_str.startswith("# "):
                p = doc.add_heading(line_str.lstrip("#").strip(), level=1)
                p.paragraph_format.space_before = Pt(16)
                p.paragraph_format.space_after = Pt(6)
            elif line_str.startswith(("- ", "* ", "• ")):
                p = doc.add_paragraph(style="List Bullet")
                run = p.add_run(line_str.lstrip("-*• ").strip())
                run.font.name = "Calibri"
                run.font.size = Pt(11)
            else:
                p = doc.add_paragraph()
                run = p.add_run(line_str)
                run.font.name = "Calibri"
                run.font.size = Pt(11)
                p.paragraph_format.line_spacing = 1.15
                p.paragraph_format.space_after = Pt(6)

        doc.save(target_path)
        logger.info(f"Word document saved successfully: {target_path}")

        if target_path.exists() and target_path.stat().st_size > 0:
            size_b = target_path.stat().st_size
            return {
                "success": True,
                "result": {
                    "filename": clean_name,
                    "file_path": str(target_path),
                    "size_bytes": size_b,
                    "download_url": f"/files/word/{clean_name}"
                },
                "error": None,
                "verification": {
                    "verified": True,
                    "details": f"Word document verified on disk ({size_b} bytes)."
                }
            }
        return {
            "success": False,
            "result": None,
            "error": "Word document was not written to disk.",
            "verification": {"verified": False, "details": "Post-save verification failed."}
        }
    except Exception as e:
        logger.error(f"Failed to create Word document '{clean_name}': {e}")
        return {
            "success": False,
            "result": None,
            "error": f"Document generation error: {str(e)}",
            "verification": {"verified": False, "details": "Exception during generation."}
        }
