"""
PowerPoint Presentation (.pptx) Generator for Ayush AI using python-pptx.
Creates professional slides saved directly into files/ppt/.
"""

from typing import List, Dict, Any
from pathlib import Path
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from config import PPT_DIR
from agent.permissions import validate_safe_path
from agent.logger import logger


def create_powerpoint(filename: str, slides: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Generates a formatted PowerPoint presentation in files/ppt/.
    Each slide dictionary can have:
      {"title": "...", "content": "bullet 1\nbullet 2\n..."}
    """
    clean_name = filename.strip()
    if not clean_name.endswith(".pptx"):
        clean_name += ".pptx"

    target_path = validate_safe_path(PPT_DIR / clean_name, allowed_roots=[PPT_DIR])
    logger.info(f"Generating PowerPoint '{clean_name}' with {len(slides)} slides at {target_path}")

    try:
        prs = Presentation()
        # Set 16:9 widescreen dimensions (10 x 5.625 inches)
        prs.slide_width = Inches(13.333)
        prs.slide_height = Inches(7.5)

        title_slide_layout = prs.slide_layouts[0]
        content_slide_layout = prs.slide_layouts[1]

        # Colors
        NAVY = RGBColor(31, 78, 121)
        GRAY = RGBColor(90, 90, 90)

        # 1. Generate Title Slide
        first_slide_data = slides[0] if slides else {"title": "Ayush AI Presentation", "content": ""}
        main_title = first_slide_data.get("title", "Presentation")
        main_subtitle = first_slide_data.get("content", "Generated by Ayush AI Personal Assistant")

        title_slide = prs.slides.add_slide(title_slide_layout)
        title_box = title_slide.shapes.title
        subtitle_box = title_slide.placeholders[1]

        title_box.text = main_title
        for p in title_box.text_frame.paragraphs:
            p.font.size = Pt(40)
            p.font.bold = True
            p.font.color.rgb = NAVY
            p.alignment = PP_ALIGN.CENTER

        subtitle_box.text = main_subtitle or "Ayush AI Assistant"
        for p in subtitle_box.text_frame.paragraphs:
            p.font.size = Pt(20)
            p.font.color.rgb = GRAY
            p.alignment = PP_ALIGN.CENTER

        # 2. Subsequent Content Slides
        subsequent_slides = slides[1:] if len(slides) > 1 else []
        for s_idx, slide_data in enumerate(subsequent_slides, start=2):
            slide_title = slide_data.get("title", f"Slide {s_idx}")
            slide_content = slide_data.get("content", "")

            slide = prs.slides.add_slide(content_slide_layout)
            title_shape = slide.shapes.title
            body_shape = slide.placeholders[1]

            title_shape.text = slide_title
            for p in title_shape.text_frame.paragraphs:
                p.font.size = Pt(28)
                p.font.bold = True
                p.font.color.rgb = NAVY

            # Format bullet points or body text
            body_frame = body_shape.text_frame
            body_frame.clear()

            content_lines = [line.strip() for line in str(slide_content).split("\n") if line.strip()]
            if not content_lines:
                content_lines = ["No content specified."]

            for line_idx, line in enumerate(content_lines):
                p = body_frame.add_paragraph() if line_idx > 0 else body_frame.paragraphs[0]
                p.text = line.lstrip("-*• ")
                p.font.size = Pt(18)
                p.space_after = Pt(10)
                p.level = 0

        prs.save(target_path)
        total_slides = 1 + len(subsequent_slides)
        logger.info(f"PowerPoint file saved: {target_path} ({total_slides} slides)")

        if target_path.exists() and target_path.stat().st_size > 0:
            size_b = target_path.stat().st_size
            return {
                "success": True,
                "result": {
                    "filename": clean_name,
                    "file_path": str(target_path),
                    "slide_count": total_slides,
                    "size_bytes": size_b,
                    "download_url": f"/files/ppt/{clean_name}"
                },
                "error": None,
                "verification": {
                    "verified": True,
                    "details": f"PowerPoint presentation verified on disk ({size_b} bytes, {total_slides} slides)."
                }
            }
        return {
            "success": False,
            "result": None,
            "error": "PowerPoint presentation was not written to disk.",
            "verification": {"verified": False, "details": "Post-save verification failed."}
        }
    except Exception as e:
        logger.error(f"Failed to create PowerPoint '{clean_name}': {e}")
        return {
            "success": False,
            "result": None,
            "error": f"PowerPoint generation error: {str(e)}",
            "verification": {"verified": False, "details": "Exception during generation."}
        }
